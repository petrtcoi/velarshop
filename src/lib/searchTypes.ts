/** Формат компактного индекса поиска (public: /search-index.json). Без зависимостей, безопасно для клиентского бандла. */
export type SearchModelEntry = {
	/** id / код модели: 3057, p30v, r32v */
	i: string
	/** заголовок */
	t: string
	/** ссылка */
	h: string
	/** тип: c трубчатые, d дизайн, r ретро, v конвектор, f напольный */
	k: 'c' | 'd' | 'r' | 'v' | 'f'
	/** ориентация: v вертикальная, h горизонтальная (если задана) */
	o?: 'v' | 'h'
	/** высоты, мм (уникальные, по возрастанию), строки как в данных */
	H: string[]
	/** межосевые расстояния, мм */
	S: string[]
	/** цена от, руб. */
	p: number
}

export type SearchPageEntry = {
	/** заголовок */
	t: string
	/** ссылка */
	h: string
	/** короткое описание */
	d?: string
	/** дополнительные слова для поиска */
	w?: string
}

export type SearchIndex = {
	m: SearchModelEntry[]
	/** разделы и подборки */
	s: SearchPageEntry[]
	/** статьи и новости */
	a: SearchPageEntry[]
}

